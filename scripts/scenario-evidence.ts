// Evidence for docs/PLAN.md acceptance points: runs both phase-3 scenarios on
// the captured OSM data (test/fixtures/scenarios) and writes what a tap would
// show on a weekday morning and on a Sunday morning, local time.
//
//   npx tsx scripts/scenario-evidence.ts > docs/evidence/scenarios-v1.md
//
// AI is off here (no key in this sandbox), so this is the seed-brand, rules-only
// pipeline; live runs add the top-down AI plan and AI checks of uncertain places.
import { existsSync, readFileSync } from "node:fs";
import path from "node:path";
import { evaluateHours, loadOpeningHours } from "../lib/openingHours";
import { ACCEPTANCE_POINTS, DEFAULT_SCENARIOS } from "../lib/scenarios/defaults";
import { runPipeline } from "../lib/scenarios/pipeline";
import { iberianTimeZone, localWallClock, rankAndTier, type ShownItem } from "../lib/scenarios/tiers";

const dir = path.join(__dirname, "..", "test", "fixtures", "scenarios");
// Thursday 12 Nov 2026 and Sunday 15 Nov 2026, 09:30 UTC (10:30 in Spain, 09:30 in Portugal).
const WEEKDAY = new Date("2026-11-12T09:30:00Z");
const SUNDAY = new Date("2026-11-15T09:30:00Z");

const km = (m: number) => (m < 1000 ? `${m} m` : `${(m / 1000).toFixed(1)} km`);
const line = (i: ShownItem) =>
  `${i.name}${i.brand && !i.name.includes(i.brand) ? ` (${i.brand})` : ""} · ${i.tierLabel} · ${km(i.distance)} · ${i.hours.label}${i.verdict !== "real" ? ` · ${i.verdict}` : ""}`;

async function main() {
  const OH = await loadOpeningHours();
  const out: string[] = [];
  out.push("# Scenario pipeline v1 — evidence on the acceptance points", "");
  out.push(
    "Generated by `scripts/scenario-evidence.ts` from OpenStreetMap data captured into `test/fixtures/scenarios/` (15 km stop radius, captured dates in each file).",
    "AI was **off** (no DeepSeek key in the build sandbox): seed brand lists + rules only. Live runs add the AI top-down plan and AI checks of uncertain places.",
    "No web search (free tier): \"real\" rests on map evidence (chain brand, opening hours, contact, recent edits). Open/closed is evaluated from the mapped opening hours in local time.",
    "",
  );
  for (const s of DEFAULT_SCENARIOS) {
    out.push(`## ${s.icon} ${s.title}`, "");
    for (const p of ACCEPTANCE_POINTS) {
      const file = path.join(dir, `${p.slug}--${s.slug}.json`);
      out.push(`### ${p.name}`, "");
      if (!existsSync(file)) {
        out.push("_No captured data (Overpass mirror did not answer) — not evaluated._", "");
        continue;
      }
      const fx = JSON.parse(readFileSync(file, "utf8"));
      const run = await runPipeline({
        scenario: { slug: s.slug, prompt: s.prompt, config: s.config },
        stop: { lat: p.lat, lng: p.lng, radiusKm: fx.radiusKm, country: p.country, area: p.area },
        langs: [],
        ai: null,
        overpass: async () => fx.elements,
        now: WEEKDAY,
      });
      const real = run.items.filter((i) => i.verdict === "real").length;
      out.push(
        `Captured ${fx.capturedAt.slice(0, 10)}: ${fx.elements.length} OSM elements → ${run.items.length} places (${real} real, ${run.items.length - real} unverified), ${run.dropped.length} dropped.`,
      );
      const bu = run.notes.find((n) => n.step === "bottom-up");
      const chains = bu?.message.match(/chains not in the brand list: (.*?)\./)?.[1];
      if (chains) out.push(`Bottom-up proposals (chains not in the brand list): ${chains}.`);
      out.push("");
      const tz = iberianTimeZone(p, p.country);
      for (const [day, when] of [["Thursday", WEEKDAY], ["Sunday", SUNDAY]] as const) {
        const now = localWallClock(when, tz);
        const label = `${day} ${now.toTimeString().slice(0, 5)}`;
        const t = rankAndTier(run.items, p, s.config, now, (i, n) => evaluateHours(OH, i.openingHours, { lat: i.lat, lng: i.lng, country: p.country }, n));
        out.push(`**${label}** (${tz})`, "");
        const section = (title: string, list: ShownItem[], max = 3) => {
          if (!list.length) return;
          out.push(`- ${title}:`);
          for (const i of list.slice(0, max)) out.push(`  - ${line(i)}`);
        };
        section("Recommended", t.recommended);
        section("Closed today ❌", t.closedToday);
        section("Small open alternatives", t.smallOpen);
        section("Unverified / hours unknown", t.unverified);
        if (!t.recommended.length && !t.closedToday.length && !t.smallOpen.length && !t.unverified.length) out.push("- Nothing found.");
        out.push("");
      }
      if (run.dropped.length) {
        out.push(`<details><summary>Dropped (${run.dropped.length})</summary>`, "");
        for (const d of run.dropped.slice(0, 8)) out.push(`- ${d.name}: ${d.reason}`);
        out.push("", "</details>", "");
      }
    }
  }
  process.stdout.write(out.join("\n") + "\n");
}

main();
