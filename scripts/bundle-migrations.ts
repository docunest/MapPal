// Copies prisma/migrations/*/migration.sql into lib/migrations.generated.ts so
// the running app can apply them itself (lib/migrate.ts) — no file reads at
// runtime, nothing for Vercel's file tracing to miss.
// Run after adding a migration: npm run migrations:bundle
// (test/migrations.test.ts fails if this file is out of date.)
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

export function readMigrations(root = path.join(__dirname, "..", "prisma", "migrations")) {
  return readdirSync(root)
    .filter((d) => existsSync(path.join(root, d, "migration.sql")))
    .sort()
    .map((name) => ({ name, sql: readFileSync(path.join(root, name, "migration.sql"), "utf8") }));
}

export function render(migrations: Array<{ name: string; sql: string }>): string {
  return (
    "// GENERATED by scripts/bundle-migrations.ts from prisma/migrations — do not edit.\n" +
    "export const MIGRATIONS: ReadonlyArray<{ name: string; sql: string }> = " +
    JSON.stringify(migrations, null, 2) +
    ";\n"
  );
}

if (require.main === module) {
  const out = path.join(__dirname, "..", "lib", "migrations.generated.ts");
  writeFileSync(out, render(readMigrations()));
  console.log(`Wrote ${out}`);
}
